glm::vec2 vueltaVertical(float u)
{
    float a = 2.0f * PI_AVION * u;
    return glm::vec2(12.0f * sin(a), 12.0f * (1.0f - cos(a)));
}

float subidaAvion(float u)
{
    // Pendientes de 45 grados con entradas y salidas redondeadas.
    float x = 90.0f * u;
    float altura = 0.0f;
    const float limites[] = {0, 4, 22, 26, 64, 68, 86, 90};
    const float pendientes[] = {0, 1, 1, 0, 0, -1, -1, 0};
    for (int i = 0; i < 7; ++i)
    {
        float largo = limites[i + 1] - limites[i];
        float t = glm::clamp((x - limites[i]) / largo, 0.0f, 1.0f);
        altura += largo * (pendientes[i] * t + (pendientes[i + 1] - pendientes[i]) *
            (t * 0.5f - sin(PI_AVION * t) / (2.0f * PI_AVION)));
    }
    return altura;
}

glm::vec2 caidaAvion(float u)
{
    // Cuatro keyframes con tangentes para redondear la subida y la recuperacion.
    const glm::vec2 puntos[] = {{0,0}, {28,68}, {48,24}, {100,0}};
    const glm::vec2 tangentes[] = {{45,0}, {6,0}, {30,-40}, {60,0}};
    float paso = glm::clamp(u, 0.0f, 1.0f) * 3.0f;
    int i = glm::min(int(paso), 2);
    float t = paso - i;
    float t2 = t * t, t3 = t2 * t;
    return (2*t3-3*t2+1)*puntos[i] + (t3-2*t2+t)*tangentes[i] +
        (-2*t3+3*t2)*puntos[i+1] + (t3-t2)*tangentes[i+1];
}

glm::vec2 perfilVuelo(const TramoVuelo& tramo, float u)
{
    if (tramo.tipo == LOOP_AVION) return vueltaVertical(u);
    if (tramo.tipo == SUBIDA_AVION) return glm::vec2(tramo.distancia*u, subidaAvion(u));
    if (tramo.tipo == CAIDA_AVION) return caidaAvion(u);
    float onda = sin(PI_AVION*u);
    return glm::vec2(tramo.distancia*u, 1.2f*onda*onda*sin(4.0f*PI_AVION*u));
}

glm::mat4 matrizAvion(float tiempo)
{
    float paso = fmod(tiempo / DURACION_TRAMO, float(TRAMOS_AVION));
    int actual = int(paso);
    float u = paso - actual, yaw = 0.0f, pitch = 0.0f;
    glm::vec3 posicion(0.0f, 20.0f, -300.0f);
    for (int i = 0; i <= actual; ++i)
    {
        float t = i == actual ? u : 1.0f;
        const TramoVuelo& tramo = recorridoAvion[i];
        if (tramo.tipo == GIRO_AVION)
        {
            float a = tramo.distancia * toRadians * t;
            posicion += glm::vec3(20*(cos(yaw)-cos(yaw+a)), 0, 20*(sin(yaw+a)-sin(yaw)));
            yaw += a;
        }
        else
        {
            glm::vec2 perfil = perfilVuelo(tramo, t);
            posicion += glm::vec3(sin(yaw)*perfil.x, perfil.y, cos(yaw)*perfil.x);
            if (i == actual)
            {
                glm::vec2 d = perfilVuelo(tramo, glm::min(t+0.001f,1.0f)) -
                    perfilVuelo(tramo, glm::max(t-0.001f,0.0f));
                pitch = tramo.tipo == LOOP_AVION ? 2*PI_AVION*t : atan2(d.y,d.x);

            }
        }
    }
    glm::mat4 model = glm::translate(glm::mat4(1.0f), posicion);
    model = glm::rotate(model, yaw + 90*toRadians, glm::vec3(0,1,0));
    return glm::rotate(model, -pitch, glm::vec3(0,0,1));
}

void actualizaAvion(float dt)
{
    tiempoAvion += dt;
    anguloHelice = fmod(anguloHelice + 1200.0f*dt, 360.0f);
    modelAvionAux = matrizAvion(tiempoAvion);
    modelHelice = glm::translate(modelAvionAux, HELICE_AVION_POS);
    modelHelice = glm::rotate(modelHelice, anguloHelice*toRadians, glm::vec3(1,0,0));
    for (auto& particula : humo) particula.edad += dt;
    emisionHumo += dt;
    while (emisionHumo >= INTERVALO_HUMO)
    {
        emisionHumo -= INTERVALO_HUMO;
        if (emisionHumo >= VIDA_HUMO) continue;
        glm::mat4 emisor = matrizAvion(tiempoAvion - emisionHumo);
        for (int ala = -1; ala <= 1; ala += 2)
        {
            ParticulaHumo& particula = humo[siguienteHumo];
            // Emisores hijos del avion; el humo emitido permanece en el mundo.
            particula.posicion = glm::vec3(emisor * glm::vec4(0.5f,0.0f,ala*4.5f,1.0f));
            particula.edad = emisionHumo;
            siguienteHumo = (siguienteHumo + 1) % MAX_HUMO;
        }
    }
}

